/** كشف التكنيكات المناسبة من آخر رسالة عميل (أو حالة متابعة) */
export function detectPsychContext(lastClientMsg: string, opts?: { followup?: boolean }): { id: string; name: string; guidance: string }[] {
  const out: { id: string; name: string; guidance: string }[] = []
  for (const r of REACTION_PLAYBOOK) {
    if (r.id === "state:silence_value_first_followup") {
      if (opts?.followup) out.push({ id: r.id, name: r.name, guidance: r.guidance })
      continue
    }
    if (r.detect.test(lastClientMsg)) out.push({ id: r.id, name: r.name, guidance: r.guidance })
  }
  return out.slice(0, 2) // تكنيكان بالكتير — التركيز أهم من التجميع
}

/** سطر توجيه نفسي جاهز للحقن في البرومبت */
export function psychReactionLine(lastClientMsg: string, opts?: { followup?: boolean }): string {
  const hits = detectPsychContext(lastClientMsg, opts)
  if (!hits.length) return ""
  return `الوضع النفسي دلوقتي — استخدم التكنيك ده (وذكّر نفسك إن رد العميل ده مش كلام عادي ده سلوك نفسي):
${hits.map((h) => `【${h.name}】\n${h.guidance}`).join("\n\n")}`
}

