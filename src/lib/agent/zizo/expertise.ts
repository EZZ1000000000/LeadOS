/** حقن الخبرة الميدانية في برومبت زيزو — حسب كلام العميل (مختصر ومركّز) */
export function expertiseBrief(text: string): string {
  const pbs = matchPlaybooks(text).slice(0, 2)
  if (!pbs.length) return ""
  return pbs
    .map(
      (p) =>
        `خبرتك في ${p.name}:\n• تأطير القيمة: ${p.hook}\n• سؤال استكشاف مناسب: ${p.questions[0]}\n• اعتراض متوقع وردّه: «${p.objections[0].q}» → ${p.objections[0].a}\n• إغلاق مناسب: ${p.close}`,
    )
    .join("\n\n")
}

/** رصد الاعتراض/الموقف التفاوضي */
export function detectNegotiation(text: string): NegotiationMove | null {
  if (!text) return null
  for (const m of NEGOTIATION_LAB) if (m.trigger.test(text)) return m
  return null
}

/** حقن توجيه التفاوض (لو فيه اعتراض) — يُستخدم جنب طبقة النفس */
export function objectionBrief(text: string): string {
  const m = detectNegotiation(text)
  if (!m) return ""
  return `وضع تفاوضي مكتشف — 【${m.name}】:\n${m.guidance}`
}

// ─── السَمّ في ذاكرة زيزو (AgentInsight) — idempotent ───
async function seedIfMissing(wsId: string, kind: string, pattern: string, note: string): Promise<boolean> {
  const existing = await db.agentInsight.findFirst({ where: { workspaceId: wsId, kind, pattern } })
  if (existing) return false
  await db.agentInsight.create({
    data: { workspaceId: wsId, kind, pattern: pattern.slice(0, 120), note: note.slice(0, 400), weight: 1 },
  })
  return true
}

/** سَمّ خبرة البيع كاملة: الإحصائيات الموثقة + أسعار مصر + Playbooks الـ17 + قواعد التواصل + مكتبة الإغلاق */
export async function seedExpertiseKnowledge(wsId: string): Promise<number> {
  let n = 0
  for (const s of REAL_STATS) {
    if (await seedIfMissing(wsId, "expertise", `إحصائية موثقة: ${s.stat.slice(0, 90)}`, `${s.stat} — إمتى تستخدمها: ${s.use}`)) n++
  }
  for (const p of EGYPT_PRICES) {
    if (await seedIfMissing(wsId, "expertise", `سعر سوق مصري: ${p.service}`, p.anchor)) n++
  }
  for (const p of FIELD_PLAYBOOKS) {
    if (
      await seedIfMissing(
        wsId,
        "expertise",
        `خبرة ميدانية: ${p.name}`,
        `تأطير: ${p.hook.slice(0, 160)} — إغلاق: ${p.close.slice(0, 110)} — رد على «${p.objections[0].q}»: ${p.objections[0].a.slice(0, 160)}`,
      )
    )
      n++
  }
  for (const c of CLOSING_LIBRARY) {
    if (await seedIfMissing(wsId, "expertise", `تقنية إغلاق: ${c.name}`, `إمتى: ${c.when} — الصياغة: «${c.line}»`)) n++
  }
  if (await seedIfMissing(wsId, "expertise", "قواعد التواصل البارد", OUTREACH_RULES.slice(0, 400))) n++
  return n
}

